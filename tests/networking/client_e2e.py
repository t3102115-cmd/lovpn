"""End-to-end client gate: real client broker/engine and WireGuard in a sandbox.

Run only via ``scripts/test-networking.sh``.  The caller supplies the host network
namespace only so this test can prove it is not running on the host; the test itself
runs in the caller's disposable user+network+pid namespace.  A child network namespace
holds the client daemon and its veth uplink, while the caller's namespace holds the
server and its veth to the upstream echo service.

This gate deliberately uses the public CLI for offline enrollment and for every client
operation.  The private key is generated by ``lovpn identity generate`` and is only
ever passed by path to the CLI; it is never read or printed by this test.
"""

